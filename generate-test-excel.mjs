// 简单估算每个学生两个月累计节数
function countConsumed(rows) {
  const m = {};
  rows.forEach(r => {
    const count = r[4];
    const names = String(r[5]).split(/[,，;；、/\s]+/).filter(Boolean);
    names.forEach(n => {
      m[n] = (m[n] ?? 0) + count;
    });
  });
  return m;
}

