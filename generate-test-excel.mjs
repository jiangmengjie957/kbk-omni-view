// Excel 1900 epoch 基准：1899-12-30 = 序列号 0
// 2026-05-01 的序列号：Date.UTC(1899,11,30) 起算的天数
function dateToSerial(year, month, day) {
  const base = Date.UTC(1899, 11, 30);
  const target = Date.UTC(year, month - 1, day);
  return Math.round((target - base) / (24 * 60 * 60 * 1000));
}

